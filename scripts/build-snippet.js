import * as esbuild from 'esbuild';
import * as fs from 'fs';
import * as zlib from 'zlib';
import * as path from 'path';

async function build() {
  const distDir = path.resolve(process.cwd(), 'dist');
  if (!fs.existsSync(distDir)) {
    fs.mkdirSync(distDir, { recursive: true });
  }

  const result = await esbuild.build({
    entryPoints: ['src/tracker/snippet.ts'],
    bundle: true,
    minify: true,
    format: 'iife',
    target: ['es2020'],
    write: false
  });

  const code = result.outputFiles[0].text;
  const outPath = path.join(distDir, 'quhip.js');
  fs.writeFileSync(outPath, code, 'utf-8');

  // Gzip compression check
  const gzipped = zlib.gzipSync(Buffer.from(code, 'utf-8'));
  const rawSizeKb = (Buffer.byteLength(code, 'utf-8') / 1024).toFixed(2);
  const gzipSizeKb = (gzipped.length / 1024).toFixed(2);

  console.log(`[Snippet Build] Output: ${outPath}`);
  console.log(`[Snippet Build] Raw size: ${rawSizeKb} KB`);
  console.log(`[Snippet Build] Gzipped size: ${gzipSizeKb} KB (Budget: < 10 KB)`);

  if (gzipped.length > 10 * 1024) {
    throw new Error(`Snippet exceeds 10 KB gzipped limit! Current: ${gzipSizeKb} KB`);
  }

  // Also write a generated TypeScript file containing the minified snippet as an exported string
  // so the Cloudflare Worker can serve it at GET /quhip.js with zero filesystem dependencies!
  const generatedTs = `// Auto-generated by scripts/build-snippet.js - DO NOT EDIT MANUALLY
export const SNIPPET_CODE = ${JSON.stringify(code)};
export const SNIPPET_RAW_SIZE_KB = ${JSON.stringify(rawSizeKb)};
export const SNIPPET_GZIP_SIZE_KB = ${JSON.stringify(gzipSizeKb)};
`;
  fs.writeFileSync(path.resolve(process.cwd(), 'src/tracker/generated-snippet.ts'), generatedTs, 'utf-8');
  console.log(`[Snippet Build] Generated src/tracker/generated-snippet.ts successfully.`);
}

build().catch((err) => {
  console.error('[Snippet Build Failed]', err);
  process.exit(1);
});
